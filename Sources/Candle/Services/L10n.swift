    public static func knowYearToggleKey(for eventType: EventType) -> Key {
        switch eventType {
        case .birthday: return .knowBirthYear
        case .anniversary: return .knowAnniversaryYear
        case .nameday: return .knowNamedayYear
        case .special: return .knowEventYear
        }
    }
    
    public static func eventDateLabelKey(for eventType: EventType) -> Key {
        switch eventType {
        case .birthday: return .birthDateLabel
        case .anniversary: return .anniversaryDateLabel
        case .nameday: return .namedayDateLabel
        case .special: return .eventDateLabel
        }
    }
    
    public static func onEventDayKey(for eventType: EventType, recurrence: EventRecurrence? = nil) -> Key {
        switch eventType {
        case .birthday:
            return .onBirthdayDay
        case .anniversary:
            if recurrence == .monthly {
                return .onMesiversaryDay
            }
            return .onAnniversaryDay
        case .nameday:
            return .onNamedayDay
        case .special:
            return .onSpecialEventDay
        }
    }
    
    public static func onEventDayKey(for person: BirthdayPerson) -> Key {
        onEventDayKey(for: person.eventType, recurrence: person.recurrence)
    }
